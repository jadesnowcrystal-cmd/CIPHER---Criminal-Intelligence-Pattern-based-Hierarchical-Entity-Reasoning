# ==========================================
# TIMELINE ENGINE & MULTI-FILE INGESTION LOGIC
# ==========================================

class TimelineCorrelationEngine:
    """
    Ingests and transforms data from .csv and .txt output files generated by
    main_investigation_pipeline.py into chronologically structured timelines.
    """

    EVENT_COLOR_MAP = {
        "Occurrence": "#EF4444",        # Crimson / Incident Occurrence
        "FIR Report": "#F59E0B",        # Amber / Reporting Time
        "Call (CDR)": "#3B82F6",        # Blue / Telecom Voice
        "IPDR Session": "#0284C7",      # Light Blue / Web & Proxy
        "Subscriber Reg": "#06B6D4",    # Cyan / SIM Activation
        "FASTag / Vehicle": "#10B981", # Green / Toll Pass
        "ANPR Scan": "#059669",        # Emerald / Camera Scan
        "Bank Transaction": "#8B5CF6", # Purple / Banking
        "Crypto On-Chain": "#EC4899",  # Pink / Blockchain
        "Crypto KYC/Ramp": "#D946EF",  # Fuchsia / Exchange
        "Anomaly Alert": "#DC2626"      # Red Alert / Fraud & Mismatch
    }

    @classmethod
    def load_pipeline_data(cls) -> Dict[str, Any]:
        """Loads available CSV and TXT files generated by main_investigation_pipeline.py."""
        data = {}

        files_to_load = {
            "fir": "complete_fir_dataset.csv",
            "cdr": "Call_Recording.csv",
            "sdr": "Subscriber_Detail_Records.csv",
            "ipdr": "IP_Detail_Records.csv",
            "fastag": "FASTag_Toll_Logs.csv",
            "anpr": "ANPR_Camera_Feeds.csv",
            "bank": "Bank_Statement_Records.csv",
            "upi": "UPI_Payment_Gateway_Logs.csv",
            "crypto": "Crypto_OnChain_Transactions.csv",
            "crypto_ramp": "Crypto_Exchange_OnOffRamp_Logs.csv"
        }

        for key, filepath in files_to_load.items():
            if os.path.exists(filepath):
                try:
                    data[key] = pd.read_csv(filepath)
                except Exception:
                    data[key] = pd.DataFrame()
            else:
                data[key] = pd.DataFrame()

        data["txt_anomalies"] = cls._parse_text_report("FINAL_GOVERNMENT_CASE_INVESTIGATION_REPORT.txt")
        return data

    @classmethod
    def _parse_text_report(cls, filepath: str) -> List[Dict[str, Any]]:
        """Parses anomalies and findings out of the generated .txt report."""
        if not os.path.exists(filepath):
            return []

        anomalies = []
        current_case = "UNKNOWN"

        with open(filepath, "r", encoding="utf-8") as f:
            for line in f:
                line_str = line.strip()
                if "1. FIR BASIC INFORMATION - CASE ID:" in line_str:
                    match = re.search(r"CASE ID:\s*(FIR/\d+/\d+|\w+)", line_str)
                    if match:
                        current_case = match.group(1)
                elif "SEVERITY:" in line_str:
                    anomalies.append({
                        "Case_ID": current_case,
                        "Details": line_str
                    })
        return anomalies

    @classmethod
    def build_case_timeline(cls, data_store: Dict[str, Any], selected_case_id: Optional[str] = None) -> pd.DataFrame:
        """Builds a combined timeline dataframe mapping events from Occurrence -> FIR Reporting -> Logs."""
        events = []

        # 1. FIR & Occurrence
        fir_df = data_store.get("fir", pd.DataFrame())
        if not fir_df.empty:
            target_fir = fir_df if not selected_case_id else fir_df[fir_df["FIR_No"] == selected_case_id]
            for _, row in target_fir.iterrows():
                case_id = str(row.get("FIR_No", "N/A"))
                place_of_occ = str(row.get("Place_of_Occurrence", "Unknown"))
                ps_location = str(row.get("Police_Station", "Police Station"))

                report_dt_str = str(row.get("Date_Time_of_FIR", ""))
                try:
                    rep_dt = datetime.strptime(report_dt_str, "%Y-%m-%d %H:%M")
                except ValueError:
                    rep_dt = datetime.now()

                days_offset = int(row.get("Days_Offset_N", 0))
                occ_dt = rep_dt - pd.Timedelta(days=days_offset)

                events.append({
                    "Case_ID": case_id, "DateTime": occ_dt, "Date": occ_dt.strftime("%Y-%m-%d"),
                    "Time": occ_dt.strftime("%H:%M"), "Event Type": "Occurrence",
                    "Person": str(row.get("Accused_Name_Alias", "Unknown Accused")), "Location": place_of_occ,
                    "Description": f"Incident Occurrence: {row.get('Case_Type', 'Offense')} reported at {place_of_occ}.",
                    "Source": "FIR Occurrence Log", "Risk Score": 90
                })

                events.append({
                    "Case_ID": case_id, "DateTime": rep_dt, "Date": rep_dt.strftime("%Y-%m-%d"),
                    "Time": rep_dt.strftime("%H:%M"), "Event Type": "FIR Report",
                    "Person": str(row.get("Informant_Name", "Complainant")), "Location": ps_location,
                    "Description": f"FIR Registered at {ps_location} by {row.get('Informant_Name')}. Act: {row.get('Acts_Sections')}",
                    "Source": "FIR Filing Record", "Risk Score": 50
                })

        # 2. Telecom Call Records (CDR)
        cdr_df = data_store.get("cdr", pd.DataFrame())
        if not cdr_df.empty:
            target_cdr = cdr_df if not selected_case_id else cdr_df[cdr_df["Case_ID"] == selected_case_id]
            for _, row in target_cdr.iterrows():
                try:
                    c_dt = datetime.strptime(str(row.get("Call Date & Time")), "%d/%m/%Y %H:%M")
                except Exception:
                    continue

                duration = int(row.get("Duration (s)", 0))
                events.append({
                    "Case_ID": str(row.get("Case_ID")), "DateTime": c_dt, "Date": c_dt.strftime("%Y-%m-%d"),
                    "Time": c_dt.strftime("%H:%M"), "Event Type": "Call (CDR)",
                    "Person": str(row.get("Calling Number (A-Party)")), "Location": str(row.get("First Tower Location", "Cell Tower")),
                    "Description": f"Call to {row.get('Called Number (B-Party)')} ({duration}s)",
                    "Source": "CDR Logs", "Risk Score": 85 if duration < 5 else 35
                })

        # 3. Subscriber Registrations (SDR)
        sdr_df = data_store.get("sdr", pd.DataFrame())
        if not sdr_df.empty:
            target_sdr = sdr_df if not selected_case_id else sdr_df[sdr_df["Case_ID"] == selected_case_id]
            for _, row in target_sdr.iterrows():
                act_str = str(row.get("Activation Date & Time", "")).replace(" IST", "")
                try:
                    s_dt = datetime.strptime(act_str, "%d-%b-%Y %H:%M:%S")
                except Exception:
                    continue

                events.append({
                    "Case_ID": str(row.get("Case_ID")), "DateTime": s_dt, "Date": s_dt.strftime("%Y-%m-%d"),
                    "Time": s_dt.strftime("%H:%M"), "Event Type": "Subscriber Reg",
                    "Person": str(row.get("Subscriber Name")), "Location": str(row.get("Local Address", "RTO / Telecom Circle")),
                    "Description": f"SIM Activation: {row.get('Mobile Number')} ({row.get('Service Provider / Circle')})",
                    "Source": "SDR Database", "Risk Score": 20
                })

        # 4. Internet Protocol Records (IPDR)
        ipdr_df = data_store.get("ipdr", pd.DataFrame())
        if not ipdr_df.empty:
            target_ipdr = ipdr_df if not selected_case_id else ipdr_df[ipdr_df["Case_ID"] == selected_case_id]
            for _, row in target_ipdr.iterrows():
                try:
                    i_dt = datetime.strptime(str(row.get("Session Start Time")), "%d/%m/%Y %H:%M:%S")
                except Exception:
                    continue

                src_ip = str(row.get("Source Public IP"))
                is_tor = src_ip in ["185.220.101.4", "185.220.101.5", "103.211.54.12"]
                events.append({
                    "Case_ID": str(row.get("Case_ID")), "DateTime": i_dt, "Date": i_dt.strftime("%Y-%m-%d"),
                    "Time": i_dt.strftime("%H:%M"), "Event Type": "Anomaly Alert" if is_tor else "IPDR Session",
                    "Person": str(row.get("Allocated Private IP")), "Location": f"Public IP: {src_ip}",
                    "Description": f"Data Session: {row.get('Volume Out (Bytes)')} bytes transferred via {row.get('RAT Type')}",
                    "Source": "IPDR Logs", "Risk Score": 95 if is_tor else 25
                })

        # 5. Vehicle FASTag Toll Passages
        fastag_df = data_store.get("fastag", pd.DataFrame())
        if not fastag_df.empty:
            target_fastag = fastag_df if not selected_case_id else fastag_df[fastag_df["Case_ID"] == selected_case_id]
            for _, row in target_fastag.iterrows():
                try:
                    v_dt = datetime.strptime(str(row.get("Timestamp (IST)")), "%Y-%m-%d %H:%M:%S")
                except Exception:
                    continue

                is_mismatch = str(row.get("ANPR Cross-Match")) == "MISMATCH"
                events.append({
                    "Case_ID": str(row.get("Case_ID")), "DateTime": v_dt, "Date": v_dt.strftime("%Y-%m-%d"),
                    "Time": v_dt.strftime("%H:%M"), "Event Type": "Anomaly Alert" if is_mismatch else "FASTag / Vehicle",
                    "Person": str(row.get("Vehicle Registration")), "Location": str(row.get("Toll Plaza ID & Location")),
                    "Description": f"Vehicle crossed toll plaza. Status: {row.get('Txn Status')}",
                    "Source": "FASTag Feed", "Risk Score": 95 if is_mismatch else 40
                })

        # 6. ANPR Camera Scans
        anpr_df = data_store.get("anpr", pd.DataFrame())
        if not anpr_df.empty:
            target_anpr = anpr_df if not selected_case_id else anpr_df[anpr_df["Case_ID"] == selected_case_id]
            for _, row in target_anpr.iterrows():
                try:
                    a_dt = datetime.strptime(str(row.get("Detection Time")), "%Y-%m-%d %H:%M:%S")
                except Exception:
                    continue

                flag = str(row.get("Investigation Flag", "PASS"))
                is_alert = flag != "PASS"
                events.append({
                    "Case_ID": str(row.get("Case_ID")), "DateTime": a_dt, "Date": a_dt.strftime("%Y-%m-%d"),
                    "Time": a_dt.strftime("%H:%M"), "Event Type": "Anomaly Alert" if is_alert else "ANPR Scan",
                    "Person": str(row.get("Captured Plate")), "Location": str(row.get("Camera ID & Location")),
                    "Description": f"ANPR Scan ({row.get('Vehicle Color & Class')}). Flag: {flag}",
                    "Source": "ANPR Feed", "Risk Score": 90 if is_alert else 30
                })

        # 7. Bank & UPI Transactions
        bank_df = data_store.get("bank", pd.DataFrame())
        if not bank_df.empty:
            target_bank = bank_df if not selected_case_id else bank_df[bank_df["Case_ID"] == selected_case_id]
            for _, row in target_bank.iterrows():
                try:
                    b_dt = datetime.strptime(str(row.get("Transaction_DateTime")), "%Y-%m-%d %H:%M:%S")
                except Exception:
                    continue

                events.append({
                    "Case_ID": str(row.get("Case_ID")), "DateTime": b_dt, "Date": b_dt.strftime("%Y-%m-%d"),
                    "Time": b_dt.strftime("%H:%M"), "Event Type": "Bank Transaction",
                    "Person": str(row.get("Person")), "Location": "Banking System",
                    "Description": f"{row.get('Type_CR_DR')} Rs.{row.get('Amount_INR')} via {row.get('Channel')} to {row.get('Counterparty_Name')}",
                    "Source": "Bank Statements", "Risk Score": 65
                })

        # 8. Crypto On-Chain Transfers
        crypto_df = data_store.get("crypto", pd.DataFrame())
        if not crypto_df.empty:
            target_crypto = crypto_df if not selected_case_id else crypto_df[crypto_df["Case_ID"] == selected_case_id]
            for _, row in target_crypto.iterrows():
                try:
                    cr_dt = datetime.strptime(str(row.get("Timestamp")), "%Y-%m-%d %H:%M:%S")
                except Exception:
                    continue

                events.append({
                    "Case_ID": str(row.get("Case_ID")), "DateTime": cr_dt, "Date": cr_dt.strftime("%Y-%m-%d"),
                    "Time": cr_dt.strftime("%H:%M"), "Event Type": "Crypto On-Chain",
                    "Person": str(row.get("Sender_Wallet"))[:10] + "...", "Location": str(row.get("Blockchain")),
                    "Description": f"Transfer: {row.get('Amount')} {row.get('Asset')} to {row.get('Receiver_Wallet')[:10]}...",
                    "Source": "Blockchain Ledger", "Risk Score": 80
                })

        # 9. Crypto On/Off-Ramp Log
        ramp_df = data_store.get("crypto_ramp", pd.DataFrame())
        if not ramp_df.empty:
            target_ramp = ramp_df if not selected_case_id else ramp_df[ramp_df["Case_ID"] == selected_case_id]
            for _, row in target_ramp.iterrows():
                try:
                    rm_dt = datetime.strptime(str(row.get("Timestamp")), "%Y-%m-%d %H:%M:%S")
                except Exception:
                    continue

                events.append({
                    "Case_ID": str(row.get("Case_ID")), "DateTime": rm_dt, "Date": rm_dt.strftime("%Y-%m-%d"),
                    "Time": rm_dt.strftime("%H:%M"), "Event Type": "Crypto KYC/Ramp",
                    "Person": str(row.get("Account_UID")), "Location": "Exchange Off-Ramp",
                    "Description": f"{row.get('Type')}: {row.get('Amount')} {row.get('Asset')} via {row.get('Channel')}",
                    "Source": "Exchange Ledger", "Risk Score": 85
                })

        if not events:
            return pd.DataFrame()

        df = pd.DataFrame(events)
        df["DateTime"] = pd.to_datetime(df["DateTime"])
        return df.sort_values("DateTime")

