# STREAMLIT UI RENDERER: TIMELINE PAGE
# ==========================================

def render_timeline_page():
    st.markdown("## Multi-Source Case Timeline Analysis")
    st.caption("Extracted automatically from CSV logs and TXT investigation summaries")

    data_store = TimelineCorrelationEngine.load_pipeline_data()
    fir_df = data_store.get("fir", pd.DataFrame())

    if fir_df.empty:
        st.warning("No CSV data found. Please run your data pipeline first.")
        return

    available_cases = ["All Cases"] + list(fir_df["FIR_No"].unique())
    selected_case = st.selectbox("Select Specific Case ID to Inspect:", options=available_cases)

    case_filter = None if selected_case == "All Cases" else selected_case
    timeline_df = TimelineCorrelationEngine.build_case_timeline(data_store, selected_case_id=case_filter)

    if timeline_df.empty:
        st.info("No correlated timeline events available for this selection.")
        return

    st.sidebar.markdown("### Filter Timeline View")
    event_types = list(timeline_df["Event Type"].unique())
    selected_types = st.sidebar.multiselect("Event Types:", options=event_types, default=event_types)

    filtered_df = timeline_df[timeline_df["Event Type"].isin(selected_types)]

    st.subheader("Interactive Multi-Event Chronology Chart")
    fig = px.scatter(
        filtered_df,
        x="DateTime",
        y="Person",
        color="Event Type",
        size="Risk Score",
        hover_data={"Case_ID": True, "Location": True, "Description": True, "Source": True, "Risk Score": True},
        color_discrete_map=TimelineCorrelationEngine.EVENT_COLOR_MAP,
        title=f"Incident Timeline & Sequence ({selected_case})"
    )

    fig.update_traces(marker=dict(symbol="circle", line=dict(width=1, color="DarkSlateGrey")))
    fig.update_layout(
        xaxis_title="Timeline",
        yaxis_title="Entity / Involved Person / Vehicle / Address",
        height=450,
        template="plotly_dark"
    )

    st.plotly_chart(fig, use_container_width=True)

    c1, c2, c3, c4 = st.columns(4)
    c1.metric("Total Extracted Events", len(filtered_df))
    c2.metric("Involved Entities", filtered_df["Person"].nunique())
    c3.metric("Primary Location", filtered_df["Location"].mode()[0] if not filtered_df.empty else "N/A")
    c4.metric("Max Risk Score", f"{filtered_df['Risk Score'].max() if not filtered_df.empty else 0}/100")

    st.subheader("Correlated Event Data Table")
    display_df = filtered_df[[
        "Case_ID", "Date", "Time", "Event Type", "Person",
        "Location", "Description", "Source", "Risk Score"
    ]].copy()

    st.dataframe(
        display_df,
        column_config={
            "Risk Score": st.column_config.ProgressColumn(
                "Risk Severity", format="%d", min_value=0, max_value=100
            )
        },
        use_container_width=True,
        hide_index=True
    )

    txt_anomalies = data_store.get("txt_anomalies", [])
    if txt_anomalies:
        st.subheader("Automated Report Intelligence Flags (.txt Summary)")
        relevant_anomalies = [
            a for a in txt_anomalies if case_filter is None or a["Case_ID"] == case_filter
        ]
        if relevant_anomalies:
            for item in relevant_anomalies[:5]:
                st.error(f"**[{item['Case_ID']}]**: {item['Details']}")
        else:
            st.success("No automated report anomalies detected for this case.")

NETWORK_REPORT_PATH = "network_analytics_report.json"
INTELLIGENCE_REPORT_PATH = "intelligence_report.json"
NETWORK_MAP_HTML_PATH = "network_map.html"

def _load_json(path: str) -> Optional[Dict[str, Any]]:
    if not os.path.exists(path):
        return None
    try:
        with open(path, "r", encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return None

def render_network_intelligence_page():
    st.markdown("## Criminal Network & Intelligence Overview")
    st.caption("Generated by network and intelligence analytics engine")

    net_report = _load_json(NETWORK_REPORT_PATH)
    intel_report = _load_json(INTELLIGENCE_REPORT_PATH)

    if not net_report and not intel_report:
        st.warning("No analysis output found. Please run your network analytics script first.")
        return

    if net_report:
        s = net_report.get("summary", {})
        c1, c2, c3, c4 = st.columns(4)
        c1.metric("Entities (Nodes)", s.get("total_nodes", 0))
        c2.metric("Relationships (Edges)", s.get("total_edges", 0))
        c3.metric("Critical Bridges", s.get("critical_bridge_count", 0))
        c4.metric("Cells / Communities", s.get("community_count", 0))

    if intel_report:
        m = intel_report.get("meta", {})
        c1, c2 = st.columns(2)
        c1.metric("Intelligence Alerts", m.get("alert_count", 0))
        c2.metric("Critical / High Severity", m.get("critical_or_high_alerts", 0))

    if os.path.exists(NETWORK_MAP_HTML_PATH):
        st.subheader("Interactive Network Map")
        with open(NETWORK_MAP_HTML_PATH, "r", encoding="utf-8") as f:
            components.html(f.read(), height=650, scrolling=True)

    if net_report and net_report.get("top_suspects"):
        st.subheader("Key Individuals Ranked by Network Influence")
        suspects_df = pd.DataFrame(net_report["top_suspects"])
        
        expected_cols = ["label", "risk_tier", "composite_score", "degree", "betweenness", "community_id"]
        for col in expected_cols:
            if col not in suspects_df.columns:
                suspects_df[col] = "N/A"
                
        df = suspects_df[expected_cols].rename(columns={
            "label": "Name", 
            "risk_tier": "Risk Tier", 
            "composite_score": "Influence Score",
            "degree": "Degree Centrality",
            "betweenness": "Betweenness Centrality",
            "community_id": "Community ID"
        })
        st.dataframe(df, use_container_width=True, hide_index=True)

    if intel_report and intel_report.get("alerts"):
        st.subheader("Suspicious Pattern Alerts")
        severity_filter = st.multiselect(
            "Filter by severity:", options=["critical", "high", "medium", "low"],
            default=["critical", "high"]
        )
        for a in intel_report["alerts"]:
            if a["severity"] not in severity_filter:
                continue
            label = f"[{a['severity'].upper()}] {a['alert_type']} (score {a['score']})"
            if a["severity"] in ("critical", "high"):
                st.error(f"**{label}**  \n{a['summary']}")
            else:
                st.warning(f"**{label}**  \n{a['summary']}")

if __name__ == "__main__":
    st.set_page_config(page_title="Investigation Intelligence Suite", layout="wide")
    tab1, tab2 = st.tabs(["Case Timeline", "Network & Intelligence"])
    with tab1:
        render_timeline_page()
    with tab2:
        render_network_intelligence_page()
