# NETWORK & INTELLIGENCE PAGE (NEW)
# ==========================================
# Surfaces the output of the new sihrelationship.py / sihnetworkanalytics.py /
# sihintelligenceengine.py modules -- the "visual and analytical insights"
# and "key individuals / suspicious patterns" the problem statement asks
# for. Reads the JSON/HTML files those modules already write, so this page
# has no analysis logic of its own -- it's a pure viewer.

NETWORK_REPORT_PATH = "network_analytics_report.json"
INTELLIGENCE_REPORT_PATH = "intelligence_report.json"
NETWORK_MAP_HTML_PATH = "network_map.html"


def _load_json(path: str) -> Optional[Dict[str, Any]]:
    if not os.path.exists(path):
        return None
    try:
        with open(path, "r", encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return None


def render_network_intelligence_page():
    st.markdown("## Criminal Network & Intelligence Overview")
    st.caption("Generated by sihrelationship.py -> sihnetworkanalytics.py -> sihintelligenceengine.py")

    net_report = _load_json(NETWORK_REPORT_PATH)
    intel_report = _load_json(INTELLIGENCE_REPORT_PATH)

    if not net_report and not intel_report:
        st.warning(
            "No analysis output found. Run `python main_investigation_pipeline.py` "
            "(it now runs the analysis modules automatically), or run "
            "`python sihrelationship.py`, `python sihnetworkanalytics.py`, and "
            "`python sihintelligenceengine.py` in that order."
        )
        return

    # 1. Headline metrics
    if net_report:
        s = net_report["summary"]
        c1, c2, c3, c4 = st.columns(4)
        c1.metric("Entities (Nodes)", s.get("total_nodes", 0))
        c2.metric("Relationships (Edges)", s.get("total_edges", 0))
        c3.metric("Critical Bridges", s.get("critical_bridge_count", 0))
        c4.metric("Cells / Communities", s.get("total_communities", 0))

    if intel_report:
        m = intel_report["meta"]
        c1, c2 = st.columns(2)
        c1.metric("Intelligence Alerts", m.get("alert_count", 0))
        c2.metric("Critical / High Severity", m.get("critical_or_high_alerts", 0))

    # 2. Interactive network graph
    if os.path.exists(NETWORK_MAP_HTML_PATH):
        st.subheader("Interactive Network Map")
        with open(NETWORK_MAP_HTML_PATH, "r", encoding="utf-8") as f:
            components.html(f.read(), height=650, scrolling=True)

    # 3. Top suspects (key individuals -- problem statement ask)
    if net_report and net_report.get("top_suspects"):
        st.subheader("Key Individuals Ranked by Network Influence")
        suspects_df = pd.DataFrame(net_report["top_suspects"])
        
        # Ensure fallback defaults if columns are missing
        expected_cols = ["label", "risk_tier", "composite_score", "degree", "betweenness"]
        for col in expected_cols:
            if col not in suspects_df.columns:
                suspects_df[col] = "N/A"
                
        df = suspects_df[expected_cols].rename(columns={
            "label": "Name", 
            "risk_tier": "Risk Tier", 
            "composite_score": "Influence Score",
            "degree": "Degree Centrality",
            "betweenness": "Betweenness Centrality"
        })
        st.dataframe(df, use_container_width=True, hide_index=True)

    # 4. Intelligence alerts
    if intel_report and intel_report.get("alerts"):
        st.subheader("Suspicious Pattern Alerts")
        severity_filter = st.multiselect(
            "Filter by severity:", options=["critical", "high", "medium", "low"],
            default=["critical", "high"]
        )
        for a in intel_report["alerts"]:
            if a["severity"] not in severity_filter:
                continue
            label = f"[{a['severity'].upper()}] {a['alert_type']} (score {a['score']})"
            if a["severity"] in ("critical", "high"):
                st.error(f"**{label}**  \n{a['summary']}")
            else:
                st.warning(f"**{label}**  \n{a['summary']}")


# Standalone Execution Entry Point
if __name__ == "__main__":
    st.set_page_config(page_title="Investigation Intelligence Suite", layout="wide")
    tab1, tab2 = st.tabs(["Case Timeline", "Network & Intelligence"])
    with tab1:
        render_timeline_page()
    with tab2:
        render_network_intelligence_page()
